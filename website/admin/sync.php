        $mode = post('sync_mode') === 'local' ? 'local' : 'cloud';
        $cloudUrl = rtrim(trim((string) post('sync_cloud_url')), '/');
        $syncToken = trim((string) post('sync_token'));
        if ($mode === 'cloud') {
            /* 云端接收端：地址不用填，密钥留空时自动生成。 */
            if ($syncToken === '') {
                $syncToken = bin2hex(random_bytes(16));
                flash('已自动生成同步密钥：' . $syncToken . '。复制到本地部署的那台保存。', 'ok');
            } else {
                flash('已保存：这台按“云端部署”使用，不需要填云端地址。', 'ok');
            }
        } else {
            if ($cloudUrl === '') {
                flash('本地部署必须填写云端网站地址，例如 https://你的域名', 'err');
                redirect('sync.php');
            }
            if ($syncToken === '') {
                flash('本地部署必须填写云端生成的同步密钥；不能留空。', 'err');
                redirect('sync.php');
            }
            flash('已保存：这台按“本地部署”使用。', 'ok');
        }
        setting_set('sync_mode', $mode);
        setting_set('sync_cloud_url', $cloudUrl);
        setting_set('sync_token', $syncToken);
        redirect('sync.php');
    }
    if (post('do') === 'gen_token') {
        /* 同一份源码：云端部署本地生成；本地部署让云端生成并自动写回。 */
        $cloudUrl = $cloud;
        if ($mode === 'local') {
            if ($cloudUrl === '') {
                flash('本地部署还没有填云端网站地址，无法让云端换密钥。', 'err');
                redirect('sync.php');
            }
            if ($token === '') {
                flash('本地还没有密钥。请先在云端生成一次并填到本地，之后这里就能一键自动换新。', 'err');
                redirect('sync.php');
            }
            [$ok, $data, $err] = sync_post_json(sync_endpoint($cloudUrl), ['action' => 'rotate_token'], $token, 12);
            $newToken = is_array($data) && !empty($data['token']) ? (string) $data['token'] : '';
            if (!$ok || $newToken === '') {
                flash('云端换密钥失败：' . ($err !== '' ? $err : '云端没有返回新密钥'), 'err');
                redirect('sync.php');
            }
            setting_set('sync_token', $newToken);
            flash('云端已生成新密钥，并自动写回本地；两边现在一致，不用再复制。', 'ok');
            redirect('sync.php');
        }
        setting_set('sync_token', bin2hex(random_bytes(16)));
        flash('已生成新的同步密钥。复制到本地站保存，两边要一致。');
        redirect('sync.php');
    }
}

