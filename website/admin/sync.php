    setting_set('sync_mode', $mode);
}

/* 已经是云端部署时，打开本页就生成密钥，不用再点保存。 */
$autoGeneratedToken = false;
if ($_SERVER['REQUEST_METHOD'] !== 'POST' && $mode === 'cloud' && $token === '') {
    $token = bin2hex(random_bytes(16));
    setting_set('sync_token', $token);
    $autoGeneratedToken = true;
}

/** 读取本地待同步的基础数据 */
function sync_local_base(): array
{
    sg_icons_ensure_table();
    sg_categories_ensure_bg();
    $icons = [];
    foreach (fetch_all('SELECT * FROM `' . T('icons') . '` ORDER BY id ASC') as $ic) {
        $icons[] = [
            'code' => 'c' . (int) $ic['id'],
            'name' => (string) $ic['name'],
            'note' => (string) $ic['note'],
            'sort' => (int) $ic['sort'],
            'image' => sync_image_pack((string) $ic['file']),
        ];
    }
    $cats = [];
    foreach (fetch_all('SELECT * FROM `' . T('categories') . '` ORDER BY sort ASC, id ASC') as $c) {
        $cats[] = [
            'name' => (string) $c['name'],
            'slug' => (string) $c['slug'],
            'icon' => (string) $c['icon'],
            'bg' => sync_image_pack((string) ($c['bg'] ?? '')),
            'sort' => (int) $c['sort'],
            'status' => (int) $c['status'],
        ];
    }
    $ings = [];
    foreach (fetch_all('SELECT * FROM `' . T('ingredients') . '` ORDER BY sort ASC, id ASC') as $ing) {
        $ings[] = [
            'name' => (string) $ing['name'],
            'sort' => (int) $ing['sort'],
            'image' => sync_image_pack((string) $ing['image']),
        ];
    }
    return ['icons' => $icons, 'categories' => $cats, 'ingredients' => $ings];
}

/** 读取本地单条菜谱及其子数据 */
function sync_local_recipe(int $id): ?array
{
    $r = fetch_one('SELECT * FROM `' . T('recipes') . '` WHERE id = ?', [$id]);
    if (!$r) {
        return null;
    }
    $catSlug = '';
    if ((int) $r['category_id'] > 0) {
        $catSlug = (string) fetch_val('SELECT slug FROM `' . T('categories') . '` WHERE id = ?', [(int) $r['category_id']], '');
    }
    $ings = [];
    foreach (fetch_all('SELECT * FROM `' . T('recipe_ingredients') . '` WHERE recipe_id = ? ORDER BY sort ASC, id ASC', [$id]) as $ing) {
        $ings[] = ['name' => (string) $ing['name'], 'quantity' => (string) $ing['quantity'], 'sort' => (int) $ing['sort']];
    }
    $steps = [];
    foreach (fetch_all('SELECT * FROM `' . T('recipe_steps') . '` WHERE recipe_id = ? ORDER BY step_no ASC, id ASC', [$id]) as $st) {
        $steps[] = [
            'step_no' => (int) $st['step_no'],
            'title' => (string) $st['title'],
            'content' => $st['content'],
            'duration' => (string) $st['duration'],
            'image' => sync_image_pack((string) $st['image']),
        ];
    }
    $tags = [];
    foreach (fetch_all('SELECT t.name FROM `' . T('recipe_tags') . '` rt JOIN `' . T('tags') . '` t ON t.id = rt.tag_id WHERE rt.recipe_id = ?', [$id]) as $t) {
        $tags[] = (string) $t['name'];
    }
    $slug = trim((string) $r['slug']) ?: sync_make_slug((string) $r['title'], 'recipe');
    return [
        'local_id' => $id,
        'title' => (string) $r['title'],
        'slug' => $slug,
        'summary' => (string) $r['summary'],
        'category_slug' => $catSlug,
        'difficulty' => (string) $r['difficulty'],
        'prep_minutes' => (int) $r['prep_minutes'],
        'cook_minutes' => (int) $r['cook_minutes'],
        'servings' => (string) $r['servings'],
        'author_name' => (string) $r['author_name'],
        'tips' => $r['tips'],
        'nutrition' => (string) $r['nutrition'],
        'status' => (string) $r['status'],
        'is_featured' => (int) $r['is_featured'],
        'published_at' => $r['published_at'],
        'views' => (int) $r['views'],
        'cover_image' => sync_image_pack((string) $r['cover']),
        'ingredients' => $ings,
        'steps' => $steps,
        'tags' => $tags,
    ];
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_GET['ajax'])) {
    header('Content-Type: application/json; charset=utf-8');
    if (!hash_equals(csrf_token(), (string) ($_SERVER['HTTP_X_CSRF_TOKEN'] ?? ''))) {
        http_response_code(419);
        echo json_encode(['ok' => false, 'msg' => '页面已过期，请刷新后重试'], JSON_UNESCAPED_UNICODE);
        exit;
    }
    $endpoint = sync_endpoint((string) setting('sync_cloud_url', ''));
    $tk = (string) setting('sync_token', '');
    if ($endpoint === '' || $tk === '') {
        echo json_encode(['ok' => false, 'msg' => '请先填写云端地址和同步密钥并保存'], JSON_UNESCAPED_UNICODE);
        exit;
    }
    $action = (string) ($_GET['ajax'] ?? '');
    try {
        if ($action === 'ping') {
            [$ok, $data, $err] = sync_post_json($endpoint, ['action' => 'ping'], $tk, 15);
        } elseif ($action === 'push_base') {
            $base = sync_local_base();
            $base['action'] = 'base';
            [$ok, $data, $err] = sync_post_json($endpoint, $base, $tk, 45);
        } elseif ($action === 'push_recipe') {
            $id = (int) ($_GET['id'] ?? 0);
            $recipe = sync_local_recipe($id);
            if (!$recipe) {
                echo json_encode(['ok' => false, 'msg' => '本地菜谱不存在：#' . $id], JSON_UNESCAPED_UNICODE);
                exit;
            }
            [$ok, $data, $err] = sync_post_json($endpoint, ['action' => 'recipe', 'recipe' => $recipe], $tk, 45);
        } else {
            echo json_encode(['ok' => false, 'msg' => '未知操作'], JSON_UNESCAPED_UNICODE);
            exit;
        }
        if ($ok) {
            echo json_encode(['ok' => true, 'data' => $data], JSON_UNESCAPED_UNICODE);
        } else {
            echo json_encode(['ok' => false, 'msg' => $err ?: '同步失败'], JSON_UNESCAPED_UNICODE);
        }
    } catch (Throwable $ex) {
        echo json_encode(['ok' => false, 'msg' => $ex->getMessage()], JSON_UNESCAPED_UNICODE);
    }
    exit;
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_verify();
